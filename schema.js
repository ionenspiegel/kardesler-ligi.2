'use strict';
// Tek yerde tanımlı şema (server.js ve scripts/import-backup.js kullanır).
// Yalnızca "IF NOT EXISTS": mevcut tablolara dokunulmaz, hiçbir şey DROP edilmez.
// KL_PREFIX yalnızca testler içindir (izole geçici tablolar); üretimde varsayılan "kl_" kullanılır.
module.exports = (P = 'kl_') => {
  if (!/^[a-z][a-z0-9_]{0,30}$/.test(P)) throw new Error('KL_PREFIX geçersiz');
  const t = { ADMIN: P + 'admin', TEAMS: P + 'teams', MATCHES: P + 'matches', SETTINGS: P + 'settings', SECRETS: P + 'secret' };
  t.DDL = [
    `CREATE TABLE IF NOT EXISTS ${t.ADMIN}(id INTEGER PRIMARY KEY CHECK(id=1),username TEXT NOT NULL,salt TEXT NOT NULL,hash TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS ${t.TEAMS}(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL UNIQUE,short TEXT,color TEXT NOT NULL DEFAULT '#22c55e')`,
    `CREATE TABLE IF NOT EXISTS ${t.MATCHES}(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,week INTEGER NOT NULL DEFAULT 1,
      home_id INTEGER NOT NULL REFERENCES ${t.TEAMS}(id) ON DELETE CASCADE,away_id INTEGER NOT NULL REFERENCES ${t.TEAMS}(id) ON DELETE CASCADE,
      hs INTEGER NOT NULL DEFAULT 0,aws INTEGER NOT NULL DEFAULT 0,played INTEGER NOT NULL DEFAULT 0,updated TEXT)`,
    `CREATE TABLE IF NOT EXISTS ${t.SETTINGS}(k TEXT PRIMARY KEY,v TEXT)`,
    `CREATE TABLE IF NOT EXISTS ${t.SECRETS}(k TEXT PRIMARY KEY,v TEXT NOT NULL)`,
  ];
  return t;
};
